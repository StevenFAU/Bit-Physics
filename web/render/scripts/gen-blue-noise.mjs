// Generate the 64×64 blue-noise dither texture used by @bp/render's
// composite pass (00-foundation.md § 3.1). Void-and-cluster (Ulichney 1993)
// on a torus with a Gaussian energy filter, sigma = 1.5. Deterministic: the
// initial binary pattern comes from a fixed integer hash, so re-running this
// script reproduces src/blue-noise-64.ts byte-for-byte.
//
//   node web/render/scripts/gen-blue-noise.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const N = 64;
const SIZE = N * N;
const SIGMA = 1.5;
const R = 8; // kernel radius (beyond 5 sigma the weight is negligible)

function mix32(x) {
  x ^= x >>> 16; x = Math.imul(x, 0x7feb352d) >>> 0;
  x ^= x >>> 15; x = Math.imul(x, 0x846ca68b) >>> 0;
  x ^= x >>> 16; return x >>> 0;
}

const kernel = [];
for (let dy = -R; dy <= R; dy += 1)
  for (let dx = -R; dx <= R; dx += 1)
    kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);

const energy = new Float64Array(SIZE);
const on = new Uint8Array(SIZE);
function splat(i, sign) {
  const x = i % N, y = (i / N) | 0;
  for (const [dx, dy, w] of kernel) {
    const j = ((y + dy + N) % N) * N + ((x + dx + N) % N);
    energy[j] += sign * w;
  }
}
const tightestCluster = () => {
  let best = -1, bi = -1;
  for (let i = 0; i < SIZE; i += 1) if (on[i] && energy[i] > best) { best = energy[i]; bi = i; }
  return bi;
};
const largestVoid = () => {
  let best = Infinity, bi = -1;
  for (let i = 0; i < SIZE; i += 1) if (!on[i] && energy[i] < best) { best = energy[i]; bi = i; }
  return bi;
};

// 1. initial pattern: ~10% of pixels, hashed
const initial = Math.round(SIZE * 0.1);
let placed = 0;
for (let k = 0; placed < initial; k += 1) {
  const i = mix32(k * 2654435761 + 12345) % SIZE;
  if (!on[i]) { on[i] = 1; splat(i, +1); placed += 1; }
}
// 2. relax: move the tightest cluster pixel into the largest void until stable
for (let iter = 0; iter < SIZE; iter += 1) {
  const c = tightestCluster();
  on[c] = 0; splat(c, -1);
  const v = largestVoid();
  if (v === c) { on[c] = 1; splat(c, +1); break; }
  on[v] = 1; splat(v, +1);
}
const prototype = on.slice();
const protoEnergy = energy.slice();
const rank = new Int32Array(SIZE).fill(-1);
// 3. phase 1: remove cluster pixels, ranks initial-1 .. 0
let ones = initial;
for (let r = ones - 1; r >= 0; r -= 1) {
  const c = tightestCluster();
  on[c] = 0; splat(c, -1); rank[c] = r;
}
// 4. phases 2+3: from the prototype, fill voids, ranks initial .. SIZE-1
on.set(prototype); energy.set(protoEnergy);
for (let r = ones; r < SIZE; r += 1) {
  const v = largestVoid();
  on[v] = 1; splat(v, +1); rank[v] = r;
}
const bytes = new Uint8Array(SIZE);
for (let i = 0; i < SIZE; i += 1) bytes[i] = Math.floor((rank[i] * 256) / SIZE);
const b64 = Buffer.from(bytes).toString("base64");
const lines = b64.match(/.{1,96}/g).map((l) => `  "${l}"`).join(" +\n");
const out = `// GENERATED by web/render/scripts/gen-blue-noise.mjs — do not edit.
// 64×64 blue-noise ranks (void-and-cluster, Gaussian sigma ${SIGMA}, torus), one byte per texel.
export const BLUE_NOISE_SIZE = ${N};
export const BLUE_NOISE_64_BASE64 =
${lines};
`;
writeFileSync(fileURLToPath(new URL("../src/blue-noise-64.ts", import.meta.url)), out);
console.log(`wrote blue-noise-64.ts (${SIZE} texels)`);
