def flat_interface_ic(
    nx: int, ny: int, rho_v: float, rho_l: float, x0: float, x1: float, width: float
) -> np.ndarray:
    """Liquid slab x in [x0, x1] between vapor, tanh-smoothed (f64)."""
    x = np.arange(nx, dtype=np.float64)[:, None]
    prof = 0.5 * (np.tanh((x - x0) / width) - np.tanh((x - x1) / width))
    rho = rho_v + (rho_l - rho_v) * prof
    return np.repeat(rho, ny, axis=1)


def droplet_ic(
    nx: int,
    ny: int,
    rho_out: float,
    rho_in: float,
    cx: float,
    cy: float,
    rx: float,
    ry: float,
    width: float,
    seed_eps: float = 0.0,
) -> np.ndarray:
    """Elliptical droplet (rx = ry for circles), tanh interface; optional
    deterministic seeded asymmetry (spec § 9 guard 3) via a fixed harmonic."""
    x = np.arange(nx, dtype=np.float64)[:, None]
    y = np.arange(ny, dtype=np.float64)[None, :]
    r = np.sqrt(((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2) * min(rx, ry)
    rho = rho_out + (rho_in - rho_out) * 0.5 * (
        1.0 - np.tanh((r - min(rx, ry)) / width)
    )
    if seed_eps:
        rho = rho * (
            1.0 + seed_eps * np.sin(2.0 * np.pi * x / nx) * np.cos(2.0 * np.pi * y / ny)
        )
    return rho


def bulk_pressure_field(rho: np.ndarray, psi: np.ndarray, g: float) -> np.ndarray:
    """p = rho cs^2 + (G cs^2/2) psi^2 — evaluated on measured fields."""
    return rho * CS2 + 0.5 * g * CS2 * psi * psi


